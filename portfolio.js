// ======================================================

function initHeroReveal() {
  const titleEl = document.getElementById("heroTitle");
  if (!titleEl) return;

  const text = titleEl.textContent.trim();
  titleEl.innerHTML = text
    .split("")
    .map(ch => `<span class="char">${ch === " " ? "&nbsp;" : ch}</span>`)
    .join("");

  const chars = titleEl.querySelectorAll(".char");
  const fadeEls = document.querySelectorAll("[data-hero-fade]");

  if (window.gsap) {
    const tl = gsap.timeline({ delay: 0.35 });
    tl.to(chars, {
      y: "0%",
      duration: 1,
      stagger: 0.028,
      ease: "power4.out"
    }).to(fadeEls, {
      opacity: 1,
      duration: 0.9,
      stagger: 0.12,
      ease: "power2.out"
    }, "-=0.5");
  } else {
    chars.forEach(c => c.style.transform = "translateY(0)");
    fadeEls.forEach(el => el.style.opacity = 1);
  }
}


// ======================================================
// COMPTEURS DE STATISTIQUES
// ======================================================

function initCounters() {
  const counters = document.querySelectorAll(".stat-number");
  if (!counters.length) return;

  const animateCounter = (el) => {
    const target = parseInt(el.dataset.count, 10) || 0;
    const suffix = el.dataset.suffix || "";
    const duration = 1200;
    const start = performance.now();

    function tick(now) {
      const progress = Math.min((now - start) / duration, 1);
      const eased = 1 - Math.pow(1 - progress, 3);
      el.textContent = Math.round(eased * target) + suffix;
      if (progress < 1) requestAnimationFrame(tick);
    }
    requestAnimationFrame(tick);
  };

  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        animateCounter(entry.target);
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.6 });

  counters.forEach(el => observer.observe(el));
}


// ======================================================
// RÉVÉLATIONS AU SCROLL (un seul système, sobre)
// ======================================================

function initScrollReveal() {
  const groups = document.querySelectorAll(".reveal-group");

  if (window.gsap && window.ScrollTrigger) {
    gsap.registerPlugin(ScrollTrigger);

    groups.forEach(group => {
      gsap.fromTo(group,
        { opacity: 0, y: 34 },
        {
          opacity: 1,
          y: 0,
          duration: 1,
          ease: "power3.out",
          scrollTrigger: {
            trigger: group,
            start: "top 82%",
            once: true
          }
        }
      );
    });

    // Barres de compétences liées au scroll
    document.querySelectorAll(".skill-fill").forEach(bar => {
      const width = bar.style.width;
      gsap.fromTo(bar, { width: "0%" }, {
        width,
        duration: 1.3,
        ease: "power3.out",
        scrollTrigger: { trigger: bar, start: "top 90%", once: true }
      });
    });
  } else {
    // Repli sans GSAP : IntersectionObserver simple
    const observer = new IntersectionObserver((entries) => {
      entries.forEach(entry => {
        if (entry.isIntersecting) {
          entry.target.style.transition = "opacity 0.8s ease, transform 0.8s ease";
          entry.target.style.opacity = 1;
          entry.target.style.transform = "translateY(0)";
          entry.target.querySelectorAll(".skill-fill").forEach(bar => {
            const match = (bar.getAttribute("style") || "").match(/\d+/);
            if (match) bar.style.width = match[0] + "%";
          });
          observer.unobserve(entry.target);
        }
      });
    }, { threshold: 0.15 });
    groups.forEach(g => observer.observe(g));
  }
}


