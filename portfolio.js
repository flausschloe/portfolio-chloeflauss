function openModal(index) {
  const project = projectsData[index];
  if (!project) return;
  const modal = document.getElementById("projectModal");
  if (!modal) return;

  const modalImage = document.getElementById("modalImage");
  if (modalImage) { modalImage.src = project.image; modalImage.alt = project.title; }

  const modalCategory = document.getElementById("modalCategory");
  if (modalCategory) modalCategory.textContent = project.category;

  const modalTitle = document.getElementById("modalTitle");
  if (modalTitle) modalTitle.textContent = project.title;

  const modalDescription = document.getElementById("modalDescription") || document.getElementById("modalDesc");
  if (modalDescription) modalDescription.textContent = project.description;

  const modalMeta = document.getElementById("modalMeta");
  if (modalMeta) {
    modalMeta.innerHTML = project.meta
      .map(item => `
        <div class="meta-item modal-meta-item">
          <span class="meta-label modal-meta-label">${item.label}</span>
          <span class="meta-value modal-meta-value">${item.value}</span>
        </div>
      `).join("");
  }

  const modalTags = document.getElementById("modalTags");
  if (modalTags) {
    modalTags.innerHTML = project.tags.map(tag => `<span class="tag modal-tag">${tag}</span>`).join("");
  }

  const modalGallery = document.getElementById("modalGallery");
  if (modalGallery) {
    if (project.gallery && project.gallery.length > 0) {
      modalGallery.style.display = "block";
      modalGallery.innerHTML = `
        <div class="modal-gallery-title">Galerie</div>
        <div class="modal-gallery-grid">
          ${project.gallery.map((item, galleryIndex) => {
            const image = typeof item === "string" ? item : item.image;
            const link = typeof item === "object" && item.link ? item.link : "";
            return `
              <div class="modal-gallery-thumb" data-gallery-index="${galleryIndex}" data-gallery-image="${image}" data-gallery-link="${link}">
                <img src="${image}" alt="${project.title}" loading="lazy" />
                <div class="gallery-thumb-overlay">
                  <svg viewBox="0 0 24 24" width="20" height="20">
                    <path fill="white" d="M15.5 14h-.79l-.28-.27A6.471 6.471 0 0 0 16 9.5 6.5 6.5 0 1 0 9.5 16 c1.61 0 3.09-.59 4.23-1.57 l.27.28v.79l5 4.99L20.49 19l-4.99-5z" />
                  </svg>
                </div>
              </div>
            `;
          }).join("")}
        </div>
      `;

      modalGallery.querySelectorAll(".modal-gallery-thumb").forEach(thumb => {
        thumb.addEventListener("click", () => {
          const galleryIndex = parseInt(thumb.dataset.galleryIndex, 10);
          const item = project.gallery[galleryIndex];
          if (typeof item === "object" && item.link) {
            window.open(item.link, "_blank");
            return;
          }
          openLightbox(project.gallery, galleryIndex);
        });
      });
    } else {
      modalGallery.style.display = "none";
      modalGallery.innerHTML = "";
    }
  }

  modal.classList.add("open");
  document.body.style.overflow = "hidden";
}

function closeModal() {
  const modal = document.getElementById("projectModal");
  if (!modal) return;
  modal.classList.remove("open");
  document.body.style.overflow = "";
}


