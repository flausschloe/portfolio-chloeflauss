class PhotoCoverflow {

  constructor() {

    this.allItems =
      Array.from(
        document.querySelectorAll(
          ".coverflow-item"
        )
      );

    this.indicatorsWrap =
      document.getElementById(
        "indicators"
      );

    this.currentIndex =
      0;

    /*
     * Pas de catégorie "Tout".
     * Le premier filtre affiché
     * dans ton HTML doit correspondre
     * à cette valeur.
     */
    this.currentFilter =
      "IAG";

    this.visibleItems =
      [];

    this.isPlaying =
      false;

    this.autoPlayInterval =
      null;

    this.autoPlaySpeed =
      4000;

    this.init();
  }


  // ====================================================
  // INITIALISATION
  // ====================================================

  init() {

    this.applyFilter(
      this.currentFilter,
      {
        skipAnimation: true
      }
    );

    this.bindEvents();
  }


  // ====================================================
  // ÉVÉNEMENTS
  // ====================================================

  bindEvents() {

    const prevBtn =
      document.getElementById(
        "prevBtn"
      );

    if (prevBtn) {
      prevBtn.addEventListener(
        "click",
        () => this.prev()
      );
    }

    const nextBtn =
      document.getElementById(
        "nextBtn"
      );

    if (nextBtn) {
      nextBtn.addEventListener(
        "click",
        () => this.next()
      );
    }

    const playPauseBtn =
      document.getElementById(
        "playPauseBtn"
      );

    if (playPauseBtn) {
      playPauseBtn.addEventListener(
        "click",
        () =>
          this.toggleAutoPlay()
      );
    }


    // --------------------------------------------------
    // FILTRES
    // --------------------------------------------------

    document
      .querySelectorAll(
        ".filter-btn"
      )
      .forEach((btn) => {

        btn.addEventListener(
          "click",
          () => {

            document
              .querySelectorAll(
                ".filter-btn"
              )
              .forEach(
                (b) =>
                  b.classList.remove(
                    "active"
                  )
              );

            btn.classList.add(
              "active"
            );

            const filter =
              btn.dataset.filter;

            this.applyFilter(
              filter
            );
          }
        );

      });


    // --------------------------------------------------
    // CLIC PROJETS
    // --------------------------------------------------

    this.allItems.forEach(
      (item) => {

        item.addEventListener(
          "click",
          () => {

            const visibleIndex =
              this.visibleItems.indexOf(
                item
              );

            if (
              visibleIndex === -1
            ) {
              return;
            }

            const originalIndex =
              parseInt(
                item.dataset.index,
                10
              );

            /*
             * Le projet central ouvre
             * la modale.
             *
             * Les autres projets
             * deviennent centraux.
             */

            if (
              visibleIndex ===
              this.currentIndex
            ) {

              openModal(
                originalIndex
              );

            } else {

              this.goTo(
                visibleIndex
              );

            }

          }
        );

      }
    );


    // --------------------------------------------------
    // CLAVIER COVERFLOW
    // --------------------------------------------------

    document.addEventListener(
      "keydown",
      (e) => {

        const projectModal =
          document.getElementById(
            "projectModal"
          );

        const lightbox =
          document.getElementById(
            "lightbox"
          );

        if (
          projectModal &&
          projectModal.classList.contains(
            "open"
          )
        ) {
          return;
        }

        if (
          lightbox &&
          lightbox.classList.contains(
            "open"
          )
        ) {
          return;
        }

        if (
          e.key === "ArrowLeft"
        ) {
          this.prev();
        }

        if (
          e.key === "ArrowRight"
        ) {
          this.next();
        }

        if (
          e.key === " "
        ) {

          e.preventDefault();

          this.toggleAutoPlay();
        }

      }
    );


    // --------------------------------------------------
    // TOUCH / MOBILE
    // --------------------------------------------------

    let startX = 0;
    let startY = 0;

    const container =
      document.getElementById(
        "coverflowContainer"
      );

    if (container) {

      container.addEventListener(
        "touchstart",
        (e) => {

          startX =
            e.touches[0].clientX;

          startY =
            e.touches[0].clientY;

        },
        {
          passive: true
        }
      );


      container.addEventListener(
        "touchend",
        (e) => {

          if (
            !startX ||
            !startY
          ) {
            return;
          }

          const diffX =
            startX -
            e.changedTouches[0]
              .clientX;

          const diffY =
            startY -
            e.changedTouches[0]
              .clientY;

          if (
            Math.abs(diffX) >
              Math.abs(diffY) &&
            Math.abs(diffX) > 50
          ) {

            if (
              diffX > 0
            ) {

              this.next();

            } else {

              this.prev();

            }

          }

          startX = 0;
          startY = 0;

        },
        {
          passive: true
        }
      );

    }


    // --------------------------------------------------
    // REDIMENSIONNEMENT
    // --------------------------------------------------

    let resizeTimer;

    window.addEventListener(
      "resize",
      () => {

        clearTimeout(
          resizeTimer
        );

        resizeTimer =
          setTimeout(
            () => {
              this.updateCoverflow();
            },
            100
          );

      }
    );

  }


  // ====================================================
  // FILTRE
  // ====================================================

  applyFilter(
    filter,
    options = {}
  ) {

    this.currentFilter =
      filter;

    this.visibleItems =
      this.allItems.filter(
        (item) =>
          item.dataset.category ===
          filter
      );


    // --------------------------------------------------
    // AFFICHAGE / MASQUAGE
    // --------------------------------------------------

    this.allItems.forEach(
      (item) => {

        const isVisible =
          this.visibleItems.includes(
            item
          );

        item.classList.toggle(
          "filtered-out",
          !isVisible
        );

        item.style.display =
          isVisible
            ? ""
            : "none";

      }
    );


    this.currentIndex =
      0;

    this.rebuildIndicators();

    this.updateCoverflow(
      options
    );
  }


  // ====================================================
  // INDICATEURS
  // ====================================================

  rebuildIndicators() {

    if (
      !this.indicatorsWrap
    ) {
      return;
    }

    this.indicatorsWrap.innerHTML =
      this.visibleItems
        .map(
          (_, i) =>
            `
              <div
                class="indicator${
                  i === 0
                    ? " active"
                    : ""
                }"
                data-index="${i}"
              ></div>
            `
        )
        .join("");


    this.indicatorsWrap
      .querySelectorAll(
        ".indicator"
      )
      .forEach(
        (
          indicator,
          index
        ) => {

          indicator.addEventListener(
            "click",
            () =>
              this.goTo(
                index
              )
          );

        }
      );
  }


  // ====================================================
  // AFFICHAGE COVERFLOW
  // ====================================================

  updateCoverflow() {

    const isSmallMobile =
      window.innerWidth <= 480;

    const isMobile =
      window.innerWidth <= 768;

    const viewportHeight =
      window.innerHeight;

    const total =
      this.visibleItems.length;


    let baseSpacing =
      220;


    if (
      viewportHeight > 900
    ) {

      baseSpacing =
        250;

    } else if (
      viewportHeight < 768
    ) {

      baseSpacing =
        180;

    }


    if (isSmallMobile) {

      baseSpacing =
        Math.min(
          baseSpacing * 0.7,
          140
        );

    } else if (isMobile) {

      baseSpacing =
        Math.min(
          baseSpacing * 0.8,
          170
        );

    }


    this.visibleItems.forEach(
      (item, index) => {

        let offset =
          index -
          this.currentIndex;


        // ----------------------------------------------
        // ROTATION CIRCULAIRE
        // ----------------------------------------------

        if (total > 0) {

          if (
            offset >
            total / 2
          ) {

            offset -=
              total;

          } else if (
            offset <
            -total / 2
          ) {

            offset +=
              total;

          }

        }


        const translateX =
          offset *
          baseSpacing;


        let translateZ = 0;
        let rotateY = 0;
        let scale = 1;
        let opacity = 1;


        // ----------------------------------------------
        // PROJET CENTRAL
        // ----------------------------------------------

        if (
          offset === 0
        ) {

          translateZ =
            100;

          scale =
            1.1;

          item.classList.add(
            "is-center"
          );

          item.style.cursor =
            "pointer";

        } else {

          item.classList.remove(
            "is-center"
          );


          // --------------------------------------------
          // +1 / -1
          // --------------------------------------------

          if (
            Math.abs(offset) ===
            1
          ) {

            translateZ =
              0;

            rotateY =
              offset * -40;

            scale =
              0.85;

            opacity =
              0.7;


          // --------------------------------------------
          // +2 / -2
          // --------------------------------------------

          } else if (
            Math.abs(offset) ===
            2
          ) {

            translateZ =
              -100;

            rotateY =
              offset * -50;

            scale =
              0.7;

            opacity =
              0.5;


          // --------------------------------------------
          // +3 / -3
          // --------------------------------------------

          } else if (
            Math.abs(offset) ===
            3
          ) {

            translateZ =
              -150;

            rotateY =
              offset * -60;

            scale =
              0.6;

            opacity =
              0.3;


          // --------------------------------------------
          // AUTRES
          // --------------------------------------------

          } else {

            translateZ =
              -200;

            rotateY =
              offset * -70;

            scale =
              0.5;

            opacity =
              0.2;

          }

          item.style.cursor =
            "pointer";

        }


        item.style.transform =
          `translate(-50%, -50%) ` +
          `translateX(${translateX}px) ` +
          `translateZ(${translateZ}px) ` +
          `rotateY(${rotateY}deg) ` +
          `scale(${scale})`;


        item.style.opacity =
          opacity;


        item.style.zIndex =
          total -
          Math.abs(offset);

      }
    );


    // --------------------------------------------------
    // INDICATEUR ACTIF
    // --------------------------------------------------

    if (
      this.indicatorsWrap
    ) {

      this.indicatorsWrap
        .querySelectorAll(
          ".indicator"
        )
        .forEach(
          (
            indicator,
            index
          ) => {

            indicator.classList.toggle(
              "active",
              index ===
                this.currentIndex
            );

          }
        );

    }

  }


  // ====================================================
  // AUTOPLAY
  // ====================================================

  toggleAutoPlay() {

    const btn =
      document.getElementById(
        "playPauseBtn"
      );


    if (
      this.isPlaying
    ) {

      this.stopAutoPlay();

      if (btn) {

        btn.innerHTML =
          "▶";

        btn.classList.remove(
          "playing"
        );

      }

    } else {

      this.startAutoPlay();

      if (btn) {

        btn.innerHTML =
          "❚❚";

        btn.classList.add(
          "playing"
        );

      }

    }

  }


  startAutoPlay() {

    this.isPlaying =
      true;

    this.autoPlayInterval =
      setInterval(
        () =>
          this.next(),
        this.autoPlaySpeed
      );

  }


  stopAutoPlay() {

    this.isPlaying =
      false;

    if (
      this.autoPlayInterval
    ) {

      clearInterval(
        this.autoPlayInterval
      );

      this.autoPlayInterval =
        null;

    }

  }


  // ====================================================
  // PRÉCÉDENT
  // ====================================================

  prev() {

    const total =
      this.visibleItems.length;

    if (
      total === 0
    ) {
      return;
    }

    this.currentIndex =
      (
        this.currentIndex -
        1 +
        total
      ) %
      total;

    this.updateCoverflow();

  }


  // ====================================================
  // SUIVANT
  // ====================================================

  next() {

    const total =
      this.visibleItems.length;

    if (
      total === 0
    ) {
      return;
    }

    this.currentIndex =
      (
        this.currentIndex +
        1
      ) %
      total;

    this.updateCoverflow();

  }


  // ====================================================
  // ALLER À
  // ====================================================

  goTo(index) {

    if (
      index < 0 ||
      index >=
        this.visibleItems.length
    ) {
      return;
    }

    this.currentIndex =
      index;

    this.updateCoverflow();

  }

}


