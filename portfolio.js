function getProjectCover(project) {
  const image = project && project.image ? project.image : "";
  if (image && !/\.pdf(?:$|\?)/i.test(image)) return image;

  const gallery = Array.isArray(project?.gallery) ? project.gallery : [];
  const firstImage = gallery.find(item => {
    const src = typeof item === "string" ? item : item?.image;
    return src && !/\.pdf(?:$|\?)/i.test(src);
  });

  if (firstImage) return typeof firstImage === "string" ? firstImage : firstImage.image;
  return "";
}

function renderEditorialPortfolio(filter = "all") {
  const grid = document.getElementById("editorialGrid");
  if (!grid || !Array.isArray(projectsData)) return;

  const filtered = filter === "all"
    ? projectsData
    : projectsData.filter(project => project.mainCategory === filter);

  grid.innerHTML = "";

  // Six colonnes indépendantes sur grand écran :
  // cela reproduit la logique de la galerie de référence,
  // avec des images qui s'empilent naturellement dans chaque colonne.
  const columnCount = window.innerWidth <= 380 ? 1 : window.innerWidth <= 600 ? 2 : window.innerWidth <= 800 ? 3 : window.innerWidth <= 1100 ? 4 : 6;
  const columns = Array.from({ length: columnCount }, () => {
    const column = document.createElement("div");
    column.className = "editorial-column";
    grid.appendChild(column);
    return column;
  });

  filtered.forEach((project, index) => {
    const originalIndex = projectsData.indexOf(project);
    const cover = getProjectCover(project);
    if (!cover) return;

    const card = document.createElement("button");
    card.type = "button";
    card.className = "editorial-card";
    card.dataset.projectIndex = originalIndex;
    card.setAttribute("aria-label", `Voir le projet : ${project.title}`);

    const img = document.createElement("img");
    img.src = cover;
    img.alt = project.title || "Projet";
    img.loading = index < columnCount * 2 ? "eager" : "lazy";
    img.decoding = "async";

    const overlay = document.createElement("span");
    overlay.className = "editorial-card-overlay";
    overlay.innerHTML = '<span class="editorial-arrow">↗</span>';

    card.appendChild(img);
    card.appendChild(overlay);
    card.addEventListener("click", () => openModal(originalIndex));

    // Répartition verticale indépendante, comme dans le book de référence.
    columns[index % columnCount].appendChild(card);
  });
}

function initEditorialPortfolio() {
  const grid = document.getElementById("editorialGrid");
  const filters = document.querySelectorAll("#portfolioFilters .filter-btn");
  if (!grid) return;

  let currentFilter = "all";
  renderEditorialPortfolio(currentFilter);

  filters.forEach(button => {
    button.addEventListener("click", () => {
      filters.forEach(btn => btn.classList.remove("active"));
      button.classList.add("active");
      currentFilter = button.dataset.filter || "all";
      renderEditorialPortfolio(currentFilter);
    });
  });

  let resizeTimer;
  window.addEventListener("resize", () => {
    clearTimeout(resizeTimer);
    resizeTimer = setTimeout(() => renderEditorialPortfolio(currentFilter), 150);
  });
}

